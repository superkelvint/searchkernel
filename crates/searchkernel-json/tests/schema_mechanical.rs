use std::path::{Path, PathBuf};

fn walk(directory: &Path) -> Vec<PathBuf> {
    if !directory.exists() {
        return Vec::new();
    }
    std::fs::read_dir(directory)
        .unwrap()
        .flat_map(|entry| {
            let path = entry.unwrap().path();
            if path.is_dir() {
                walk(&path)
            } else {
                vec![path]
            }
        })
        .collect()
}

#[test]
fn message_specific_json_logic_is_generated_not_handwritten() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let generated = root.join("src/generated.rs");
    assert!(
        generated.exists(),
        "C6 requires src/generated.rs from searchkernel-bindgen"
    );
    let generated_text = std::fs::read_to_string(&generated).unwrap();
    assert!(generated_text.contains("@generated by searchkernel-bindgen"));

    let forbidden_message_terms = [
        "InsertRequest",
        "UpsertRequest",
        "PatchRequest",
        "SearchRequest",
        "FilterExpr",
        "QueryExpr",
        "RankingPolicy",
        "SearchResult",
    ];

    for directory in [root.join("src"), root.join("native")] {
        for path in walk(&directory) {
            if path == generated {
                continue;
            }
            let text = std::fs::read_to_string(&path).unwrap();
            for term in forbidden_message_terms {
                assert!(
                    !text.contains(term),
                    "handwritten message-specific JSON mapping term {term} found in {}",
                    path.display()
                );
            }
        }
    }
}
