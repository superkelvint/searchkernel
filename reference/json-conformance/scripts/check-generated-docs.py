#!/usr/bin/env python3
import json,re
from pathlib import Path
here=Path(__file__).resolve().parent.parent
expected=json.loads((here/'expected/operation-map.json').read_text()); text=(here/'generated/API.md').read_text(); lower=text.lower()
if '@generated by searchkernel-bindgen' not in text: raise SystemExit('API.md missing generated marker')
for op in [x['operation'] for x in expected['operations']]:
    if not re.search(rf'\b{re.escape(op)}\b',lower): raise SystemExit(f'API.md missing operation {op}')
for phrase in ['one-key','int64','uint64','decimal string','base64']:
    if phrase not in lower: raise SystemExit(f'API.md missing JSON policy: {phrase}')
print('C6 generated docs coverage PASS')
