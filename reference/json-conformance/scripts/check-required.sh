#!/usr/bin/env bash
set -euo pipefail
here=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
root=$(cd "$here/../.." && pwd)
required=(
  "$root/tools/searchkernel-bindgen/Cargo.toml"
  "$here/GENERATED_PATHS.txt"
  "$root/clients/python/searchkernel/generated/models.py"
  "$root/core/crates/searchkernel-json/src/generated.rs"
  "$root/core/crates/searchkernel-json/bfbs/searchkernel_request.bfbs"
  "$root/core/crates/searchkernel-json/bfbs/searchkernel_response.bfbs"
  "$here/expected/operation-map.json"
  "$here/expected/fixture-manifest.json"
)
for path in "${required[@]}"; do
  [[ -e "$path" ]] || { echo "C6 required artifact missing: ${path#$root/}" >&2; exit 1; }
done
for file in "$root/clients/python/searchkernel/generated/models.py" "$root/core/crates/searchkernel-json/src/generated.rs"; do
  grep -Fq '@generated by searchkernel-bindgen' "$file" || { echo "generated marker missing: ${file#$root/}" >&2; exit 1; }
done
