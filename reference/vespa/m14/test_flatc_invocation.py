#!/usr/bin/env python3
import os
import subprocess
import tempfile
from pathlib import Path

M14 = Path(__file__).resolve().parent
FIXTURE = M14 / "fixture" / "index-definition.json"
PREPARE = M14 / "prepare-portable-definition.sh"

with tempfile.TemporaryDirectory() as tmp:
    root = Path(tmp)
    shim = root / "flatc"
    shim.write_text(
        """#!/usr/bin/env python3
import sys
from pathlib import Path

args = sys.argv[1:]
if "--" in args:
    print("standalone -- rejected", file=sys.stderr)
    raise SystemExit(64)

out = Path(args[args.index("-o") + 1])
out.mkdir(parents=True, exist_ok=True)
source = Path(args[-1])
(out / "index-definition.bin").write_bytes(source.read_bytes())
""",
        encoding="utf-8",
    )
    shim.chmod(0o755)
    env = os.environ.copy()
    env["FLATC_PATH"] = str(shim)

    cases = [("fixture", FIXTURE), ("custom", root / "custom.json")]
    cases[1][1].write_text('{"custom":true}\n', encoding="utf-8")

    for name, source in cases:
        out = root / name
        proc = subprocess.run(
            [str(PREPARE), str(out), str(source)],
            env=env,
            text=True,
            capture_output=True,
            check=False,
        )
        if proc.returncode != 0:
            raise SystemExit(
                f"portable definition invocation rejected: {proc.stderr.strip()}"
            )

        generated = Path(proc.stdout.strip())
        if generated.read_bytes() != source.read_bytes():
            raise SystemExit(f"{name}: generated bytes changed")

print("M14 flatc invocation valid")
