import { describe, expect, it, vi, afterEach } from 'vitest'
import { Client, Daemon, IndexTargetT, Index as RemoteIndex, IndexDefinitionT, Text, SearchKernelError, TransportError, ResultDecodeError, fromCanonicalJson, toCanonicalJson } from '@searchkernel/client'
import { createDaemonSearchKernelClient, dashboardValue, daemonError } from './daemon-searchkernel-client'

afterEach(() => vi.restoreAllMocks())
describe('daemon dashboard boundary', () => {
  it('uses the canonical URL generation without opening or upgrading it', async () => {
    const open = vi.spyOn(RemoteIndex, 'open')
    const describe = vi.spyOn(Client.prototype, 'describe').mockResolvedValue(fromCanonicalJson('DescribeResult', { index: { name: 'old-schema' } }) as any)
    const get = vi.spyOn(Client.prototype, 'get').mockResolvedValue(fromCanonicalJson('GetResult', {}) as any)
    const client = createDaemonSearchKernelClient('http://daemon')
    const target = new IndexTargetT('alpha', 'G1')
    expect(await client.getIndex(target)).toMatchObject({ id: 'alpha', generation: 'G1', target })
    await client.getDocument(target, 'one')
    expect(open).not.toHaveBeenCalled()
    expect((describe.mock.instances[0] as unknown as Client).generation).toBe('G1')
    expect((get.mock.instances[0] as unknown as Client).generation).toBe('G1')
  })
  it('keeps old and replacement requests attached to independent bound handles', async () => {
    const definition = new IndexDefinitionT('schema')
    const oldGet = vi.fn().mockRejectedValue(new SearchKernelError('stale', fromCanonicalJson('Error', { code: 'FailedPrecondition', details: [{ code: 'stale_index_handle' }] }) as any))
    const newGet = vi.fn().mockResolvedValue(fromCanonicalJson('GetResult', {}))
    const describe = vi.fn().mockResolvedValue({ index: definition })
    const open = vi.spyOn(RemoteIndex, 'open').mockResolvedValueOnce({ definition, generation: 'G1', client: { get: oldGet, describe } } as any).mockResolvedValueOnce({ definition, generation: 'G2', client: { get: newGet, describe } } as any)
    const client = createDaemonSearchKernelClient('http://daemon')
    const old = await client.openIndex!('alpha'), fresh = await client.openIndex!('alpha')
    await expect(client.getDocument(old.target!, 'one')).rejects.toMatchObject({ details: [{ code: 'stale_index_handle' }] })
    await expect(client.getDocument(fresh.target!, 'one')).resolves.toBeUndefined()
    expect(open).toHaveBeenCalledTimes(2)
    expect(oldGet).toHaveBeenCalledOnce()
    expect(newGet).toHaveBeenCalledOnce()
  })
  it('fetches intentional daemon status and preserves the exact diagnostic structure', async () => {
    const payload = { ready: true, version: '0.1.0', native_runtime: 'linked', lifecycle: 'ready', indexes: [{ name: 'alpha', generation: 'G1', state: 'open', persisted: true, schema_name: 'schema', warning: null }], unavailable: ['counts'] }
    vi.spyOn(globalThis, 'fetch').mockImplementation(async () => new Response(JSON.stringify(payload)))
    const describe = vi.fn().mockResolvedValue(fromCanonicalJson('DescribeResult', { index: { name: 'schema' } }))
    vi.spyOn(RemoteIndex, 'open').mockResolvedValue({ definition: new IndexDefinitionT('schema'), generation: 'G1', client: { describe } } as any)
    const client = createDaemonSearchKernelClient('http://daemon')
    const index = await client.openIndex!('alpha')
    expect(await client.daemonStatus!()).toEqual(payload)
    const diagnostics = await client.indexDiagnostics!(index.target!)
    expect(JSON.parse(diagnostics.canonical)).toEqual({ status: payload.indexes[0], definition: toCanonicalJson(await describe()) })
  })
  it('rejects malformed diagnostics instead of fabricating lifecycle state', async () => {
    vi.spyOn(globalThis, 'fetch').mockImplementation(async () => new Response(JSON.stringify({ ready: true, version: '0.1', native_runtime: 'linked', lifecycle: 'ready', unavailable: [], indexes: [{ name: 'alpha', state: 'invented' }] })))
    await expect(createDaemonSearchKernelClient('http://daemon').daemonStatus!()).rejects.toMatchObject({ code: 'protocol_error', origin: 'protocol' })
  })
  it('obtains a canonical rejection when diagnostics race a replacement incarnation', async () => {
    const stale = new SearchKernelError('stale', fromCanonicalJson('Error', { code: 'FailedPrecondition', details: [{ code: 'stale_index_handle' }] }) as any)
    const describe = vi.fn().mockResolvedValueOnce(fromCanonicalJson('DescribeResult', { index: { name: 'schema' } })).mockRejectedValueOnce(stale)
    vi.spyOn(RemoteIndex, 'open').mockResolvedValue({ definition: new IndexDefinitionT('schema'), generation: 'G1', client: { describe } } as any)
    vi.spyOn(globalThis, 'fetch').mockImplementation(async () => new Response(JSON.stringify({ ready: true, version: '0.1', native_runtime: 'linked', lifecycle: 'ready', unavailable: [], indexes: [{ name: 'alpha', generation: 'G2', state: 'open', persisted: true, schema_name: 'schema', warning: null }] })))
    const client = createDaemonSearchKernelClient('http://daemon'), index = await client.openIndex!('alpha')
    await expect(client.indexDiagnostics!(index.target!)).rejects.toMatchObject({ origin: 'canonical', details: [{ code: 'stale_index_handle' }] })
    expect(describe).toHaveBeenCalledTimes(2)
  })
  it('lists without open, hydrates only the selected target, and retains its bound handle', async () => {
    vi.spyOn(Daemon.prototype, 'listIndexes').mockResolvedValue(['alpha', 'beta'])
    const get = vi.fn().mockResolvedValue(fromCanonicalJson('GetResult', { document: { id: 'one', fields: [{ key: 'title', value: { kind_type: 'StringValue', kind: { value: 'real title' } } }, { key: 'quantity', value: { kind_type: 'Int64Value', kind: { value: '9007199254740993' } } }] } }))
    const definition = new IndexDefinitionT('different-schema', [new Text({ stored: true, searchable: true }).definition('title')])
    const open = vi.spyOn(RemoteIndex, 'open').mockResolvedValue({ definition, generation: 'incarnation', client: { get } } as unknown as RemoteIndex)
    const client = createDaemonSearchKernelClient('http://daemon')
    expect(await client.listIndexes()).toEqual([{ id: 'alpha' }, { id: 'beta' }])
    expect(open).not.toHaveBeenCalled()
    expect(await client.getIndex('alpha')).toMatchObject({ id: 'alpha', generation: 'incarnation', searchDefaults: {}, profiles: [], summaries: [] })
    expect(await client.getIndex('alpha')).toMatchObject({ id: 'alpha', generation: 'incarnation' })
    expect((await client.getDocument('alpha', 'one'))?.fields.quantity).toEqual({ $type: 'integer', decimal: '9007199254740993' })
    expect(open).toHaveBeenCalledTimes(1)
    get.mockResolvedValue(fromCanonicalJson('GetResult', {}))
    expect(await client.getDocument('alpha', 'missing')).toBeUndefined()
  })
  it('does not let one cancelled metadata observer abort the shared index open', async () => {
    let resolveOpen!: (index: RemoteIndex) => void
    const openPromise = new Promise<RemoteIndex>(resolve => { resolveOpen = resolve })
    const open = vi.spyOn(RemoteIndex, 'open').mockReturnValue(openPromise)
    const client = createDaemonSearchKernelClient('http://daemon')
    const first = new AbortController()
    const cancelled = client.getIndex('alpha', { signal: first.signal })
    first.abort()
    await expect(cancelled).rejects.toMatchObject({ code: 'aborted' })

    const replacement = client.getIndex('alpha')
    resolveOpen({
      definition: new IndexDefinitionT('schema'),
      generation: 'incarnation',
    } as unknown as RemoteIndex)
    await expect(replacement).resolves.toMatchObject({ id: 'alpha', generation: 'incarnation' })
    expect(open).toHaveBeenCalledTimes(1)
    expect(open.mock.calls[0]?.[3]).toBeUndefined()
  })

  it('preserves disabled attributes and leaves script-owned capabilities unavailable', async () => {
    const disabled = new Text({ stored: true, searchable: true }).definition('title')
    Object.assign(disabled, { attribute: { enabled: { value: false } } })
    const scripted = new Text().definition('scripted')
    scripted.indexingScript = 'input scripted | index | summary'
    vi.spyOn(RemoteIndex, 'open').mockResolvedValue({
      definition: new IndexDefinitionT('schema', [disabled, scripted]), generation: 'incarnation',
    } as unknown as RemoteIndex)
    const index = await createDaemonSearchKernelClient('http://daemon').getIndex('alpha')
    expect(index?.fields[0].attribute).toBe(false)
    expect(index?.fields[1]).toMatchObject({ stored: undefined, searchable: undefined, attribute: undefined })
  })
  it('passes explicit controls and cancellation and leaves omitted defaults absent', async () => {
    const raw = fromCanonicalJson('SearchResult', { root: { node_type: 'ResultGroup', node: { children: [{ node_type: 'Hit', node: { id: 'one', relevance: { value_type: 'FiniteRelevance', value: { value: 0.75 } } } }] } }, total_hits: { value: '1', relation: 'Exact' } })
    const search = vi.fn().mockResolvedValue(raw)
    vi.spyOn(RemoteIndex, 'open').mockResolvedValue({ definition: new IndexDefinitionT(), client: { search } } as unknown as RemoteIndex)
    const client = createDaemonSearchKernelClient('http://daemon')
    const signal = new AbortController().signal
    const prepared = client.prepareSearch({ query: 'orchid', ranking: 'custom', summary: 'compact', limit: 3, offset: 2, filters: [{ field: 'quantity', operator: 'gte', value: '7' }], sorts: [{ field: 'quantity', direction: 'desc' }], inputs: '{"boost":2.5}' })
    const result = await client.executeSearch('alpha', prepared, { signal })
    const sent = search.mock.calls[0][0]
    expect(JSON.stringify(toCanonicalJson(sent), null, 2)).toBe(prepared.canonical)
    expect(search.mock.calls[0][1]).toEqual({ signal })
    expect(toCanonicalJson(sent)).toMatchObject({ ranking: { profile: 'custom' }, limit: { value: 3 }, offset: { value: 2 }, presentation: { summary: 'compact' }, filters: { structured: expect.any(Array) } })
    expect(result).toMatchObject({ matches: '1', hits: [{ document: { id: 'one' }, score: '0.75' }], canonicalResponse: JSON.stringify(toCanonicalJson(raw), null, 2) })
    expect(result.resolved).toBeUndefined()
    expect(result.analysis).toBeUndefined()
    expect(result.timingMs).toBeUndefined()
    await client.search('alpha', { query: '' })
    expect(toCanonicalJson(search.mock.calls[1][0])).toMatchObject({ query: { source_type: 'MatchAllQuery' } })
    expect((toCanonicalJson(search.mock.calls[1][0]) as any).ranking).toBeUndefined()
  })
  it('keeps stale errors structured and never silently reopens', async () => {
    const error = new SearchKernelError('stale', fromCanonicalJson('Error', { code: 'FailedPrecondition', message: 'stale', retryable: false, details: [{ code: 'stale_index_handle', path: 'target.generation', metadata: [{ key: 'target', value: 'alpha' }] }] }) as NonNullable<ConstructorParameters<typeof SearchKernelError>[1]>)
    const get = vi.fn().mockRejectedValue(error)
    const open = vi.spyOn(RemoteIndex, 'open').mockResolvedValue({ definition: new IndexDefinitionT(), client: { get } } as unknown as RemoteIndex)
    const client = createDaemonSearchKernelClient('http://daemon')
    await client.getIndex('alpha')
    await expect(client.getDocument('alpha', 'one')).rejects.toMatchObject({ origin: 'canonical', retryable: false, details: [{ code: 'stale_index_handle' }] })
    await expect(client.getDocument('alpha', 'one')).rejects.toMatchObject({ origin: 'canonical' })
    expect(open).toHaveBeenCalledOnce()
    expect(daemonError(error).details).toEqual([{ code: 'stale_index_handle', path: 'target.generation', metadata: [{ key: 'target', value: 'alpha' }] }])
    expect(daemonError(new ResultDecodeError('missing result metadata'))).toMatchObject({ origin: 'protocol' })
    expect(daemonError(new TransportError('admission', { status: 503, code: 14 }))).toMatchObject({ origin: 'transport', status: 503, details: { transportCode: 14 } })
    expect(daemonError(new TransportError('offline'))).toMatchObject({ origin: 'transport', retryable: true })
    expect(daemonError(new TransportError('cancelled', undefined, 'aborted'))).toMatchObject({ code: 'aborted', retryable: false })
  })
  it('sends the exact mutation payload through the bound public client without GET-based upsert', async () => {
    const execute = vi.fn().mockResolvedValue(fromCanonicalJson('UpsertResult', { id: 'one' }))
    const get = vi.fn()
    vi.spyOn(RemoteIndex, 'open').mockResolvedValue({ definition: new IndexDefinitionT(), generation: 'incarnation', client: { execute, get } } as unknown as RemoteIndex)
    const client = createDaemonSearchKernelClient('http://daemon')
    const signal = new AbortController().signal
    const prepared = client.prepareDocumentMutation({ operation: 'upsert', id: 'one', fields: '{"title":"real"}', operations: '[]' })
    const result = await client.executeDocumentMutation('alpha', prepared, { signal })
    expect(execute.mock.calls[0][0]).toBe('upsert')
    expect(JSON.stringify(toCanonicalJson(execute.mock.calls[0][1]), null, 2)).toBe(prepared.canonical)
    expect(execute.mock.calls[0][2]).toEqual({ signal })
    expect(result).toMatchObject({ operation: 'upsert', id: 'one', canonicalResponse: JSON.stringify({ id: 'one' }, null, 2) })
    expect(get).not.toHaveBeenCalled()
  })
  it('represents richer values without integer truncation or JSON failure', () => {
    const value = dashboardValue({ dense: [1, 2], integer: 9007199254740993n, bytes: new Uint8Array([0, 255]) })
    expect(JSON.stringify(value)).toContain('9007199254740993')
    expect(value).toMatchObject({ bytes: { $type: 'bytes', base64: 'AP8=' } })
    expect(() => dashboardValue(Symbol('unsupported'))).toThrow('Unsupported result value')
  })
})
