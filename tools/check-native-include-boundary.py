#!/usr/bin/env python3
"""Reject Vespa C++ header ownership outside the native adapter."""

import argparse
import pathlib
import re
import subprocess
import sys


INCLUDE = re.compile(r'^\s*#include\s*[<"]vespa/', re.MULTILINE)
GENERATED_BUNDLE = pathlib.Path("core/crates/searchkernel-vespa-bindings/consumer_bundle.rs")
BUNDLE_MARKER = "// @generated by tools/generate-native-consumer-bundle.py; do not edit."


def check(root: pathlib.Path) -> int:
    failures = []
    bundle = root / GENERATED_BUNDLE
    if not bundle.is_file():
        failures.append(f"{GENERATED_BUNDLE}: generated consumer bundle is missing")
    else:
        contents = bundle.read_text(encoding="utf-8")
        first_line = contents.splitlines()[0] if contents else ""
        if first_line != BUNDLE_MARKER:
            failures.append(f"{GENERATED_BUNDLE}: missing canonical generated marker")
        generated = subprocess.run(
            [sys.executable, str(root / "tools/generate-native-consumer-bundle.py"), "--check"],
            cwd=root,
            check=False,
            capture_output=True,
            text=True,
        )
        if generated.returncode != 0:
            failures.append(generated.stderr.strip() or generated.stdout.strip())

    search_roots = [root / "core/crates", root / "clients", root / "searchkerneld"]
    for search_root in search_roots:
        if not search_root.exists():
            continue
        for source in search_root.rglob("*.rs"):
            if any(part in {"target", ".git"} for part in source.parts):
                continue
            relative = source.relative_to(root)
            if relative == GENERATED_BUNDLE:
                continue
            content = source.read_text(encoding="utf-8", errors="replace")
            if INCLUDE.search(content):
                failures.append(f"{relative}: Vespa C++ headers leaked outside native adapter")

    if failures:
        print("\n".join(failures), file=sys.stderr)
        return 1
    print("native include ownership boundary passed")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=pathlib.Path, default=pathlib.Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    return check(args.root.resolve())


if __name__ == "__main__":
    raise SystemExit(main())
