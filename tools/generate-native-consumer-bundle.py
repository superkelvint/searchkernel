#!/usr/bin/env python3
"""Generate the source/tool bundle required by a packaged native bindings crate."""
from pathlib import Path
import argparse
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "core/crates/searchkernel-vespa-bindings/consumer_bundle.rs"
files = [
    "tools/resolve-native-sdk.sh", "tools/install-native-base-artifact.sh",
    "tools/native-base-release-selection.py", "tools/resolve-python.sh", "tools/resolve-rust.sh",
    "tools/native-build-fingerprint.py", "tools/check-native-runtime-closure.py", "tools/check-native-sdk-hardening.sh",
    "core/native/vespa/build-sdk.sh", "core/native/vespa/manifest.json",
]
files += [f"core/native/vespa/{name}" for name in [
    "abi.cc","document.cc","engine.cc","errors.cc","grouping.cc","hardening.cc","query.cc","search.cc","tensor.cc","update.cc",
    "file_descriptor.h","highlighting.h","searchkernel_vespa.h","searchkernel_vespa_internal.h","searchkernel_vespa_test.h","transport_owner.h",
    "searchkernel_vespa.map","searchkernel_vespa_test.map",
]]
files += [str(p.relative_to(ROOT)) for p in sorted((ROOT/"core/native/vespa/embedded_crud_cfg").iterdir()) if p.is_file()]
lines = ["// @generated by tools/generate-native-consumer-bundle.py; do not edit.\n", "pub const FILES: &[(&str, &[u8])] = &[\n"]
for rel in files:
    lines.append(f'    ({rel!r}, include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../../{rel}"))),\n'.replace("'", '"'))
lines.append("];\n")
# During cargo package the include_bytes sources disappear, so replace them with byte literals.
text = ''.join(lines)
for rel in files:
    token=f'include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../../{rel}"))'
    data=(ROOT/rel).read_text()
    hashes = '########'
    if f'\"{hashes}' in data: raise SystemExit(f'raw delimiter collision in {rel}')
    literal=f'br{hashes}\"{data}\"{hashes}'
    text=text.replace(token,literal)
parser=argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args=parser.parse_args()
if args.check:
    if not OUT.exists() or OUT.read_text() != text:
        raise SystemExit("packaged native consumer bundle is stale; run tools/generate-native-consumer-bundle.py")
else:
    OUT.write_text(text)
