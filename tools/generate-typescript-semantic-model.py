#!/usr/bin/env python3
"""Generate version-free ergonomic table and enum shapes from FlatBuffers output."""
from __future__ import annotations

import re
import sys
from pathlib import Path


def main() -> int:
    generated = Path(sys.argv[1])
    output = Path(sys.argv[2])
    tables: list[tuple[str, list[tuple[str, str, str]]]] = []
    enums: list[tuple[str, str]] = []
    for path in sorted(generated.rglob("*.ts")):
        source = path.read_text(encoding="utf-8")
        for match in re.finditer(r"export class (\w+)T implements .*?\nconstructor\((.*?)\)\{\}", source, re.S):
            name, params = match.groups()
            fields = re.findall(r"public (\w+): ([^,\n]+?)(?: = ([^,\n]+))?(?:,|\n)", params)
            tables.append((name, [(field, type_name.strip(), default or "null") for field, type_name, default in fields]))
        for match in re.finditer(r"export enum (\w+) \{(.*?)\n\}", source, re.S):
            enums.append((match.group(1), match.group(2)))
    if not tables:
        raise SystemExit(f"no FlatBuffers object tables found under {generated}")
    lines = [
        "// Generated by tools/generate-typescript-semantic-model.py; do not edit.",
        "// This version-free model deliberately contains no FlatBuffers classes.",
        "export class SemanticTable {",
        "  readonly _semanticTable = true;",
        "  constructor(readonly _schemaName: string, readonly _semanticFields: string[], args: unknown[], defaults: unknown[]) {",
        "    this._semanticFields.forEach((field, index) => { (this as any)[field] = index < args.length ? args[index] : defaults[index]; });",
        "  }",
        "}",
        "export function isSemanticTable(value: unknown): value is SemanticTable { return value instanceof SemanticTable; }",
    ]
    for name, fields in tables:
        field_names = ", ".join(repr(field) for field, _, _ in fields)
        defaults = ", ".join(default for _, _, default in fields)
        lines += [f"export class {name}T extends SemanticTable {{"]
        for field, type_name, _ in fields:
            lines.append(f"  declare {field}: {type_name};")
        lines += [
            f"  constructor(...args: any[]) {{ super({name!r}, [{field_names}], args, [{defaults}]); }}",
            "}",
        ]
    for name, body in enums:
        if name.endswith("Payload") or name.endswith("Kind") or name in {"RequestPayload", "ResponsePayload"}:
            body = re.sub(r"SearchKernel_Wire_", "", body)
        lines += [f"export enum {name} {{", body, "}"]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
