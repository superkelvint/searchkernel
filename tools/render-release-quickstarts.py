#!/usr/bin/env python3
"""Render public release quickstarts from their canonical executable sources."""

from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "release-quickstart.md"
SOURCES = {
    "Python managed-local": ("python", ROOT / "examples/release-quickstart/python.py"),
    "TypeScript / Node connect": ("javascript", ROOT / "examples/release-quickstart/typescript.mjs"),
    "Ruby connect": ("ruby", ROOT / "examples/release-quickstart/ruby.rb"),
    "Rust embedded manifest": ("toml", ROOT / "examples/release-quickstart/rust/Cargo.toml"),
    "Rust embedded program": ("rust", ROOT / "examples/release-quickstart/rust/src/main.rs"),
}


def render() -> str:
    parts = [
        "# Search Kernel release quickstarts\n\n",
        "<!-- Generated by tools/render-release-quickstarts.py. Do not edit code blocks here. -->\n\n",
        "These are the exact executable quickstarts used by clean-consumer release qualification. "
        "The source files under `examples/release-quickstart/` are authoritative.\n\n",
        "All four quickstarts execute the same schema, insert, search, filter, sort, close, "
        "reopen, and persistence scenario. Python managed-local and Rust embedded use local "
        "index paths. TypeScript/Node creates and reopens `SEARCHKERNEL_TARGET` over the daemon "
        "gRPC listener (default `127.0.0.1:50051`); Ruby creates and reopens the same logical "
        "target shape over the HTTP listener (default `http://127.0.0.1:50052`).\n\n",
        "Rust embedded builds acquire the exact qualified consumer runtime on the first Cargo build. "
        "Plain `cargo add searchkernel` enables embedded search; no SDK, Vespa installation or loader environment is required. "
        "Remote-only callers can explicitly disable default features and enable `remote`.\n\n",
    ]
    for title, (language, path) in SOURCES.items():
        source = path.read_text(encoding="utf-8").rstrip() + "\n"
        parts.extend([f"## {title}\n\n", f"```{language}\n", source, "```\n\n"])
    return "".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if actual != expected:
            raise SystemExit(
                "docs/release-quickstart.md is stale; run tools/render-release-quickstarts.py"
            )
        print("release quickstart documentation PASS")
        return 0
    OUTPUT.write_text(expected, encoding="utf-8")
    print(OUTPUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
