#!/usr/bin/env python3
import os
import pathlib
import shutil
import subprocess
import tempfile
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]
CLIENT = ROOT / "tools" / "remote-verification.sh"
DEV = ROOT / "dev"

FAKE_GH = r"""#!/usr/bin/env bash
set -euo pipefail

log=${GH_FAKE_LOG:?}
state=${GH_FAKE_STATE:?}
printf '%q ' "$@" >> "$log"
printf '\n' >> "$log"

case "${1:-}:${2:-}" in
    repo:view)
        if [[ "$*" == *"nameWithOwner"* ]]; then
            echo "superkelvint/searchkernel"
        elif [[ "$*" == *"defaultBranchRef"* ]]; then
            echo "main"
        else
            exit 2
        fi
        ;;
    api:*)
        if [[ "$*" == *"/commits/"* ]]; then
            exit "${GH_FAKE_COMMIT_STATUS:-0}"
        fi
        if [[ "$*" == *"/dispatches"* ]]; then
            status=${GH_FAKE_DISPATCH_STATUS:-0}
            [[ "$status" == 0 ]] || exit "$status"
            revision=
            operation=
            target=
            request_id=
            for arg in "$@"; do
                case "$arg" in
                    "client_payload[revision]="*) revision=${arg#*=} ;;
                    "client_payload[operation]="*) operation=${arg#*=} ;;
                    "client_payload[target]="*) target=${arg#*=} ;;
                    "client_payload[request_id]="*) request_id=${arg#*=} ;;
                esac
            done
            cat > "$state" <<EOF
revision=$revision
operation=$operation
target=$target
request_id=$request_id
EOF
            exit 0
        fi
        echo "unexpected fake gh api invocation: $*" >&2
        exit 2
        ;;
    run:list)
        # Values are generated by the client and registered target names; no
        # shell evaluation is needed to replay them.
        revision=$(sed -n 's/^revision=//p' "$state")
        operation=$(sed -n 's/^operation=//p' "$state")
        target=$(sed -n 's/^target=//p' "$state")
        request_id=$(sed -n 's/^request_id=//p' "$state")
        printf '123\t%s %s @ %s [%s]\n' "$operation" "$target" "$revision" "$request_id"
        ;;
    run:view)
        if [[ "$*" == *"--log-failed"* ]]; then
            echo "FAKE FAILED LOG" >&2
        else
            echo "https://github.com/superkelvint/searchkernel/actions/runs/123"
        fi
        ;;
    run:watch)
        exit "${GH_FAKE_WATCH_STATUS:-0}"
        ;;
    *)
        echo "unexpected fake gh invocation: $*" >&2
        exit 2
        ;;
esac
"""


class RemoteVerificationClientTest(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        base = pathlib.Path(self.temp.name)
        self.repo = base / "repo"
        self.bin = base / "bin"
        self.log = base / "gh.log"
        self.state = base / "gh.state"
        self.repo.mkdir()
        self.bin.mkdir()

        subprocess.run(["git", "init", "-q"], cwd=self.repo, check=True)
        subprocess.run(
            ["git", "config", "user.email", "test@example.invalid"],
            cwd=self.repo,
            check=True,
        )
        subprocess.run(
            ["git", "config", "user.name", "Search Kernel Test"],
            cwd=self.repo,
            check=True,
        )

        (self.repo / "tools").mkdir()
        shutil.copy2(CLIENT, self.repo / "tools" / "remote-verification.sh")
        (self.repo / "README.md").write_text("test\n", encoding="utf-8")
        subprocess.run(["git", "add", "."], cwd=self.repo, check=True)
        subprocess.run(["git", "commit", "-qm", "test"], cwd=self.repo, check=True)
        self.revision = subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=self.repo, text=True
        ).strip()

        gh = self.bin / "gh"
        gh.write_text(FAKE_GH, encoding="utf-8")
        gh.chmod(0o755)

        self.env = os.environ.copy()
        self.env["PATH"] = f"{self.bin}:{self.env['PATH']}"
        self.env["GH_FAKE_LOG"] = str(self.log)
        self.env["GH_FAKE_STATE"] = str(self.state)

    def tearDown(self):
        self.temp.cleanup()

    def run_client(self, *args, **env):
        effective = self.env.copy()
        effective.update(env)
        return subprocess.run(
            ["bash", "tools/remote-verification.sh", *args],
            cwd=self.repo,
            env=effective,
            text=True,
            capture_output=True,
        )

    def test_dispatches_exact_head_through_repository_dispatch_and_waits_for_exact_run(self):
        result = self.run_client("verify", "vespa.ranking")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn(
            "Remote run: https://github.com/superkelvint/searchkernel/actions/runs/123",
            result.stdout,
        )
        log = self.log.read_text(encoding="utf-8")
        self.assertIn("api --method POST", log)
        self.assertIn("repos/superkelvint/searchkernel/dispatches", log)
        self.assertIn("event_type=searchkernel-verification", log)
        self.assertIn(f"client_payload\\[revision\\]={self.revision}", log)
        self.assertIn("client_payload\\[operation\\]=verify", log)
        self.assertIn("client_payload\\[target\\]=vespa.ranking", log)
        self.assertIn("client_payload\\[request_id\\]=remote-", log)
        self.assertIn("run watch 123", log)

    def test_dirty_worktree_fails_before_github_dispatch(self):
        (self.repo / "README.md").write_text("dirty\n", encoding="utf-8")
        result = self.run_client("test", "ir")
        self.assertEqual(result.returncode, 2)
        self.assertIn("requires a clean worktree and index", result.stderr)
        self.assertFalse(self.log.exists())

    def test_unpushed_head_fails_closed(self):
        result = self.run_client("test", "ir", GH_FAKE_COMMIT_STATUS="1")
        self.assertEqual(result.returncode, 2)
        self.assertIn("is not available from GitHub", result.stderr)
        log = self.log.read_text(encoding="utf-8")
        self.assertNotIn("/dispatches", log)

    def test_failed_remote_run_surfaces_failed_step_logs(self):
        result = self.run_client(
            "verify", "vespa.ranking", GH_FAKE_WATCH_STATUS="1"
        )
        self.assertEqual(result.returncode, 1)
        self.assertIn("Remote verification failed", result.stderr)
        self.assertIn("FAKE FAILED LOG", result.stderr)

    def test_dev_routes_remote_before_toolchain_or_container_setup(self):
        text = DEV.read_text(encoding="utf-8")
        remote = text.index('exec bash "$ROOT/tools/remote-verification.sh"')
        image = text.index("should_use_ci_image()")
        toolchain = text.index("EXPECTED_FLATBUFFERS_VERSION=")
        self.assertLess(remote, image)
        self.assertLess(remote, toolchain)


if __name__ == "__main__":
    unittest.main()
